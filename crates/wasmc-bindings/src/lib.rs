use wasmc_lexer::SymbolInterner;
use wasmc_semantics::{SemType, SymbolEntry};

pub struct BindingGenerator<'a> {
    interner: &'a SymbolInterner,
}

#[derive(Debug, Clone)]
pub struct HostBindings {
    pub js_glue: String,
    pub ts_definitions: String,
}

impl<'a> BindingGenerator<'a> {
    pub fn new(interner: &'a SymbolInterner) -> Self {
        Self { interner }
    }

    pub fn generate_web_bindings(
        &self,
        module_name: &str,
        exported_functions: &[SymbolEntry],
    ) -> HostBindings {
        let mut js = String::new();
        let mut dts = String::new();

        js.push_str("// Auto-generated by wasmc (Direct-to-WebAssembly Systems Compiler)\n");
        js.push_str("let wasmInstance = null;\n");
        js.push_str("let wasmMemory = null;\n\n");
        js.push_str("const textEncoder = new TextEncoder();\n");
        js.push_str("const textDecoder = new TextDecoder();\n\n");

        js.push_str("export async function instantiate(wasmBytes, userImports = {}) {\n");
        js.push_str("  const imports = {\n");
        js.push_str("    env: {\n");
        js.push_str("      print: (ptr, len) => {\n");
        js.push_str("        const bytes = new Uint8Array(wasmMemory.buffer, ptr, len);\n");
        js.push_str("        console.log(textDecoder.decode(bytes));\n");
        js.push_str("      },\n");
        js.push_str("      panic: (ptr, len) => {\n");
        js.push_str("        const bytes = new Uint8Array(wasmMemory.buffer, ptr, len);\n");
        js.push_str("        throw new Error('Wasm Panic: ' + textDecoder.decode(bytes));\n");
        js.push_str("      },\n");
        js.push_str("      ...userImports.env,\n");
        js.push_str("    },\n");
        js.push_str("    ...userImports,\n");
        js.push_str("  };\n\n");
        js.push_str("  const { instance } = await WebAssembly.instantiate(wasmBytes, imports);\n");
        js.push_str("  wasmInstance = instance;\n");
        js.push_str("  wasmMemory = instance.exports.memory;\n");
        js.push_str("  return exports;\n");
        js.push_str("}\n\n");

        js.push_str("export const exports = {\n");
        js.push_str("  get memory() { return wasmMemory; },\n");

        dts.push_str("// Type definitions for ");
        dts.push_str(module_name);
        dts.push_str("\n");
        dts.push_str("export function instantiate(bytes: BufferSource | WebAssembly.Module, imports?: WebAssembly.Imports): Promise<typeof exports>;\n\n");
        dts.push_str("export namespace exports {\n");
        dts.push_str("  export const memory: WebAssembly.Memory;\n");

        for entry in exported_functions {
            let fn_name = self.interner.resolve(entry.name).unwrap_or("anon");
            if let SemType::Function { params, ret } = &entry.sem_type {
                // JS wrapper function
                js.push_str(&format!("  {}: (", fn_name));
                dts.push_str(&format!("  export function {}(", fn_name));

                for (i, p) in params.iter().enumerate() {
                    if i > 0 {
                        js.push_str(", ");
                        dts.push_str(", ");
                    }
                    js.push_str(&format!("arg{}", i));
                    dts.push_str(&format!("arg{}: {}", i, Self::ts_type(p)));
                }

                js.push_str(") => {\n");
                js.push_str(&format!("    return wasmInstance.exports.{}", fn_name));
                js.push('(');
                for (i, _) in params.iter().enumerate() {
                    if i > 0 {
                        js.push_str(", ");
                    }
                    js.push_str(&format!("arg{}", i));
                }
                js.push_str(");\n");
                js.push_str("  },\n");

                dts.push_str(&format!("): {};\n", Self::ts_type(ret)));
            }
        }

        js.push_str("};\n");
        dts.push_str("}\n");

        HostBindings {
            js_glue: js,
            ts_definitions: dts,
        }
    }

    pub fn generate_wasi_start_shim(&self, _main_func_name: &str) -> String {
        format!(
            r#"// WASI Preview 1 runner shim for wasmc
import fs from 'node:fs';
import {{ WASI }} from 'node:wasi';

const wasi = new WASI({{
  args: process.argv,
  env: process.env,
  version: 'preview1',
}});

const wasmBytes = fs.readFileSync(process.argv[2]);
const importObject = {{ wasi_snapshot_preview1: wasi.wasiImport }};

const {{ instance }} = await WebAssembly.instantiate(wasmBytes, importObject);
wasi.start(instance);
"#
        )
    }

    fn ts_type(ty: &SemType) -> &'static str {
        match ty {
            SemType::Void => "void",
            SemType::Bool => "boolean",
            SemType::I32 | SemType::U32 | SemType::I64 | SemType::U64 | SemType::F32 | SemType::F64 => "number",
            SemType::Pointer(_) => "number",
            SemType::Char => "string",
            _ => "any",
        }
    }
}
